name="wambulwa"
print(name[:4]) #the first 4
print(name[4:]) # the items after the first 4
print(name[1:5]) #we skip  the first and 5th
print(name[2:4]) #skip the first 2 and the last one
print(name[::2]) #skips by 2 digits and we pick the second digit
print(name[::3])# jumps by 3
print(name[:-1]) #skips the last item/digit
print(name[:-2]) #skips the last 2 items
print(name[::-1]) #reverses the items in the list the last becomes the first one
print(name[:])
print(name[2::])
print(name[::2])